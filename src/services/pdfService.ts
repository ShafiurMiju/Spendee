import RNHTMLtoPDF from 'react-native-html-to-pdf';
import Share from 'react-native-share';
import { Expense, Income, Tenant, RentPayment, RentCost, DateRange, CategoryBreakdown } from '../types';
import { formatCurrency, formatDate, getColorForIndex } from '../utils/formatting';

interface PDFData {
  expenses: Expense[];
  dateRange: DateRange;
  householdTotal: number;
  personalTotal: number;
  breakdowns: CategoryBreakdown[];
  totalAmount: number;
}

/**
 * Generate a PDF report from the given expense data, then open the share sheet.
 */
export async function generateExpensePDF(data: PDFData): Promise<string> {
  const {
    expenses,
    dateRange,
    householdTotal,
    personalTotal,
    breakdowns,
    totalAmount,
  } = data;

  const startStr = formatDate(dateRange.startDate);
  const endStr = formatDate(dateRange.endDate);

  const html = `
    <html>
    <head>
      <style>
        body { font-family: -apple-system, Helvetica, Arial, sans-serif; padding: 24px; color: #1a1a2e; }
        h1 { color: #4A90D9; font-size: 28px; }
        h2 { color: #333; font-size: 20px; margin-top: 24px; border-bottom: 2px solid #4A90D9; padding-bottom: 6px; }
        .meta { color: #666; font-size: 14px; margin-bottom: 16px; }
        .summary-grid { display: flex; gap: 16px; margin-bottom: 24px; }
        .summary-card { background: #f5f7fa; border-radius: 12px; padding: 16px; flex: 1; text-align: center; }
        .summary-card .label { font-size: 12px; color: #6b7280; text-transform: uppercase; }
        .summary-card .value { font-size: 24px; font-weight: 800; margin-top: 4px; }
        table { width: 100%; border-collapse: collapse; margin-top: 12px; }
        th { background: #4A90D9; color: #fff; padding: 10px 8px; text-align: left; font-size: 13px; }
        td { padding: 8px; font-size: 13px; border-bottom: 1px solid #e5e7eb; }
        tr:nth-child(even) { background: #f9fafb; }
        .cat-row { display: flex; align-items: center; gap: 8px; padding: 6px 0; }
        .cat-dot { width: 12px; height: 12px; border-radius: 6px; display: inline-block; }
        .footer { margin-top: 32px; text-align: center; color: #9ca3af; font-size: 11px; }
      </style>
    </head>
    <body>
      <h1>Spendee – Expense Report</h1>
      <p class="meta">${startStr} – ${endStr}</p>

      <div class="summary-grid">
        <div class="summary-card">
          <div class="label">Total</div>
          <div class="value">${formatCurrency(totalAmount)}</div>
        </div>
        <div class="summary-card">
          <div class="label">Household</div>
          <div class="value" style="color:#4A90D9">${formatCurrency(householdTotal)}</div>
        </div>
        <div class="summary-card">
          <div class="label">Personal</div>
          <div class="value" style="color:#FF6B6B">${formatCurrency(personalTotal)}</div>
        </div>
      </div>

      <h2>Category Summary</h2>
      ${breakdowns
        .map(
          b => `
        <div class="cat-row">
          <span class="cat-dot" style="background:${b.color}"></span>
          <span style="flex:1">${b.category}</span>
          <span style="font-weight:600">${formatCurrency(b.amount)}</span>
          <span style="color:#6b7280;width:50px;text-align:right">${b.percentage.toFixed(1)}%</span>
        </div>`,
        )
        .join('')}

      <h2>Expense List (${expenses.length} items)</h2>
      <table>
        <tr>
          <th>Date</th>
          <th>Title</th>
          <th>Category</th>
          <th>Type</th>
          <th style="text-align:right">Amount</th>
        </tr>
        ${expenses
          .map(
            e => `
          <tr>
            <td>${formatDate(e.date)}</td>
            <td>${e.title}</td>
            <td>${e.category}</td>
            <td>${e.type}</td>
            <td style="text-align:right;font-weight:600">${formatCurrency(e.amount)}</td>
          </tr>`,
          )
          .join('')}
      </table>

      <div class="footer">
        Generated by Spendee · ${new Date().toLocaleDateString()}
      </div>
    </body>
    </html>
  `;

  const options = {
    html,
    fileName: `Spendee_Report_${startStr}_${endStr}`.replace(/\s/g, '_'),
    directory: 'Documents',
  };

  const file = await RNHTMLtoPDF.convert(options);
  return file.filePath!;
}

